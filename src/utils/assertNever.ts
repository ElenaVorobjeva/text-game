// Закрывает switch по union: если добавить новый вариант типа и не обработать
// его, TypeScript подсветит вызов, а не промолчит, как это делает `default`.
// Во время выполнения сюда попадают только данные, не прошедшие проверку
// (опечатка в JSON) — такую ошибку лучше увидеть, чем проглотить.
export function assertNever(value: never): never {
  throw new Error(`Неизвестный вариант: ${JSON.stringify(value)}`);
}
